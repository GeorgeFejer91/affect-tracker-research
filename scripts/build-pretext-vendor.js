import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const output = resolve(import.meta.dirname, "../site/src/research/pretext-vendor.js");
const built = await build({ entryPoints: [resolve(import.meta.dirname, "../node_modules/@chenglou/pretext/dist/layout.js")],
  bundle: true, format: "esm", platform: "browser", minify: true, write: false, legalComments: "inline" });
const source = `// @chenglou/pretext 0.0.9, MIT. Generated by scripts/build-pretext-vendor.js.\n${built.outputFiles[0].text}`;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== source) throw new Error("Pretext vendor differs from the locked package.");
} else await writeFile(output, source);
